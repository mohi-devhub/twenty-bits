OUT = ROOT / "results/diagnosis"
PRIMARY = "Qwen/Qwen3-8B"


def read_games():
    with gzip.open(ROOT / "results/phase2/games.jsonl.gz", "rt") as f:
        return [json.loads(line) for line in f]


def error_category(error, world):
    if error.startswith("Unknown attribute:"):
        name = error.split(": ", 1)[1]
        # Code names are generated by the same base-26 convention as the table.
        codes = re.findall(
            r"(?:^|,)\s*([a-z]+)=",
            messages({"world": world.to_dict(), "noise": 0})[0]["content"]
            .split("ATTRIBUTES code=name\n")[1]
            .split("\n")[0],
        )
        return "column_code_as_attribute" if name in codes else "unknown_attribute"
    if error.startswith("Unknown item:"):
        return "name_outside_candidates"
    if error == "Expected one ASK or GUESS line.":
        return "action_format"
    if error == "Expected ).":
        return "missing_close_parenthesis"
    if error == "Expected ==.":
        return "missing_item_equality"
    if error == "Expected an expression.":
        return "missing_expression"
    if error.startswith("Unexpected text"):
        return "illegal_character_or_unclosed_quote"
    if error == "Unexpected trailing tokens.":
        return "trailing_tokens"
    return error


def outcome(turn, world):
    action = turn["action"].strip()
    if turn["is_question"] and not turn["invalid"]:
        return "valid_ASK"
    if action.startswith("GUESS: "):
        name = action[7:].strip()
        return "valid_GUESS" if name in world.names and "\n" not in action else "other"
    if turn["invalid"]:
        return "INVALID"
    return "other"


def names_in(expression):
    stack, result = [expression], set()
    while stack:
        node = stack.pop()
        if node.kind == "item":
            result.add(node.value)
        stack.extend(node.children)
    return result


def zero_reason(turn, world):
    expr = parse(turn["action"][5:].strip())
    mask = expr.evaluate(world.attributes, world.names, world.rows)
    prior = np.asarray(turn["posterior_before"])
    named = names_in(expr)
    unknown = named - set(world.names)
    mass = float(mask @ prior)
    if unknown:
        reason = "outside_candidate_set"
    elif not mask.any() or mask.all():
        reason = "other_constant_on_full_table"
    elif mass == 0 or (prior[~mask] == 0).all():
        reason = "already_eliminated_side"
    else:
        reason = "other_nearly_certain_posterior"
    return {
        "category": reason,
        "requested_category": "outside_candidate_set"
        if unknown
        else "already_eliminated_items"
        if named and all(prior[world.names.index(n)] == 0 for n in named)
        else "other",
        "table_yes_count": int(mask.sum()),
        "posterior_yes_mass": mass,
        "named_items": len(named),
        "names_outside_candidates": sorted(unknown),
        "named_items_already_eliminated": int(
            sum(prior[world.names.index(n)] == 0 for n in named if n in world.names)
        ),
    }


def cost_bridge(games, model, token_cells, rate_rows):
    rate = next(r for r in rate_rows if r["tinker_id"] == model)
    rate = {
        k: Decimal(rate[k].removeprefix("$")) / 1_000_000
        for k in ("prefill", "cached_prefill", "sample")
    }
    predicted_output = 64 if model == PRIMARY else 128
    expected_inputs = expected_outputs = forecast_turns = 0
    matched_inputs = matched_outputs = 0
    for game in games:
        cell = next(
            c
            for c in token_cells
            if (c["domain"], c["n"], c["noise"])
            == (game["domain"], game["n"], game["noise"])
        )
        prefix = cell["initial_prompt_tokens"]["max"]
        turns = 2 * math.ceil(math.log2(game["n"])) + 1
        forecast_turns += turns
        expected_inputs += (
            turns * prefix + (predicted_output + 32) * turns * (turns - 1) // 2
        )
        expected_outputs += predicted_output * turns
        actual_turns = len(game["turns"])
        matched_inputs += (
            actual_turns * prefix
            + (predicted_output + 32) * actual_turns * (actual_turns - 1) // 2
        )
        matched_outputs += predicted_output * actual_turns
    turns = [t for g in games for t in g["turns"]]
    actual_inputs = sum(t["usage"]["prompt_tokens"] for t in turns)
    actual_outputs = sum(t["usage"]["output_tokens"] for t in turns)
    hits = sum(t["usage"]["prompt_cache_hit_tokens"] for t in turns)
    actual = sum((Decimal(t["usage"]["actual_usd"]) for t in turns), Decimal(0))
    forecast = expected_inputs * rate["prefill"] + expected_outputs * rate["sample"]
    components = {
        "forecast_usd": forecast,
        "turn_count_change_usd": (matched_inputs - expected_inputs) * rate["prefill"]
        + (matched_outputs - expected_outputs) * rate["sample"],
        "input_length_change_usd": (actual_inputs - matched_inputs) * rate["prefill"],
        "output_length_change_usd": (actual_outputs - matched_outputs) * rate["sample"],
        "cache_credit_usd": hits * (rate["cached_prefill"] - rate["prefill"]),
    }
    components["rounding_usd"] = actual - sum(components.values())
    assert sum(components.values()) == actual
    invalid_turns = [t for t in turns if t["invalid"]]
    return {
        "model": model,
        "forecast_turns": forecast_turns,
        "actual_turns": len(turns),
        "forecast_input_tokens": expected_inputs,
        "actual_input_tokens": actual_inputs,
        "forecast_output_tokens": expected_outputs,
        "actual_output_tokens": actual_outputs,
        "prompt_cache_hit_tokens": hits,
        "actual_usd": str(actual),
        "bridge": {k: str(v) for k, v in components.items()},
        "invalid_turns": len(invalid_turns),
        "invalid_turn_cost_usd": str(
            sum((Decimal(t["usage"]["actual_usd"]) for t in invalid_turns), Decimal(0))
        ),
        "invalid_output_tokens": sum(
            t["usage"]["output_tokens"] for t in invalid_turns
        ),
        "invalid_cost_is_subset_not_additional": True,
    }


def transcript(game, record, filename, reason):
    parts = [
        f"# Saved Phase 2 transcript: {reason}\n",
        f"Model: `{game['model']}`. Game: `{game['game_id']}`.\n",
        f"Target, revealed for diagnosis only: `{record['world']['names'][record['target']]}`.\n",
        "The complete public chat and raw generated responses follow. No action text is shortened. Diagnostics after each response are private analysis and were not fed back to the policy.\n",
    ]
    config = json.loads((ROOT / "evals/phase2.json").read_text())
    rendering = Rendering(game["model"], config)
    initial_ids = rendering.prompt(messages(record)).to_ints()
    parts += [
        "## Actual rendered initial prompt\n",
        "This includes native role markers and any template-provided system header.\n",
        "````text\n"
        + rendering.tokenizer.decode(initial_ids, skip_special_tokens=False)
        + "\n````\n",
    ]
    for i, turn in enumerate(game["turns"]):
        parts += [
            f"## Turn {i + 1}: generated response\n",
            "````text\n" + turn["raw_model_text"] + "\n````\n",
        ]
        if turn["action"] != turn["raw_model_text"]:
            parts += [
                "Action decoded by the adapter:\n",
                "````text\n" + turn["raw_action"] + "\n````\n",
            ]
        parts += [
            "Answer delivered to the model:\n",
            "````text\n" + turn["answer"] + "\n````\n",
            f"Private diagnostic: EIG {turn['eig']:.9f}; truncated {turn['truncated']}; error `{turn.get('error', '')}`.\n",
        ]
    parts += [
        f"End: won={game['won']}, questions={game['questions']}, context_overflow={game['context_overflow']}, reward={game['reward']:.4f}.\n"
    ]
    (OUT / "transcripts" / filename).write_text("\n".join(parts))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "transcripts").mkdir(exist_ok=True)
    games = read_games()
    records = {}
    for domain, n, noise in sorted({(g["domain"], g["n"], g["noise"]) for g in games}):
        records.update({r["id"]: r for r in frozen_games(domain, n, noise, 28)})
    groups = defaultdict(list)
    for game in games:
        groups[(game["model"], game["domain"], game["n"], game["noise"])].append(game)
    cells, zeros = [], []
    for key, cell_games in sorted(groups.items()):
        counts, exclusive, errors, endings, flags = (Counter() for _ in range(5))
        for game in cell_games:
            world = World.from_dict(records[game["game_id"]]["world"])
            if game["context_overflow"]:
                endings["context_limit"] += 1
            elif game["turns"][-1]["action"].startswith("GUESS: "):
                endings["wrong_guess" if not game["won"] else "win"] += 1
            else:
                endings["budget_exhausted_without_guess"] += 1
            flags["never_guessed"] += not any(
                t["action"].startswith("GUESS: ") for t in game["turns"]
            )
            flags["invalid_heavy_at_least_half_questions"] += (
                game["invalid_count"] >= game["questions"] / 2
            )
            flags["used_all_questions"] += game["questions"] == 2 * math.ceil(
                math.log2(game["n"])
            )
            for i, turn in enumerate(game["turns"]):
                label = outcome(turn, world)
                counts[label] += 1
                counts["truncated"] += turn["truncated"]
                counts["empty"] += not turn["action"].strip()
                exclusive[
                    "truncated"
                    if turn["truncated"]
                    else "empty"
                    if not turn["action"].strip()
                    else label
                ] += 1
                if turn["invalid"]:
                    errors[error_category(turn["error"], world)] += 1
                if (
                    key[0] == PRIMARY
                    and turn["is_question"]
                    and not turn["invalid"]
                    and turn["eig"] < 1e-12
                ):
                    zeros.append(
                        {
                            "game_id": game["game_id"],
                            "turn_index": i,
                            "n": key[2],
                            "noise": key[3],
                            **zero_reason(turn, world),
                        }
                    )
        cells.append(
            {
                "model": key[0],
                "domain": key[1],
                "n": key[2],
                "noise": key[3],
                "games": len(cell_games),
                "turns": sum(len(g["turns"]) for g in cell_games),
                "outcomes": dict(counts),
                "exclusive_truncation_priority": dict(exclusive),
                "parse_errors": dict(errors),
                "endings": dict(endings),
                "overlapping_game_flags": dict(flags),
            }
        )
    measurement = json.loads((ROOT / "research/token_measurements.json").read_text())
    rates = json.loads((ROOT / "research/tinker-models-2026-11-17.json").read_text())
    costs = [
        cost_bridge(
            [g for g in games if g["model"] == model],
            model,
            measurement["models"][model]["cells"],
            rates,
        )
        for model in sorted({g["model"] for g in games})
    ]
    selected = [
        (
            next(
                g
                for g in games
                if g["model"] == PRIMARY
                and g["n"] == 32
                and g["noise"] == 0
                and all(t["invalid"] for t in g["turns"] if t["is_question"])
                and any(t["truncated"] for t in g["turns"])
            ),
            "qwen-malformed.md",
            "malformed and truncated questions",
        ),
        (
            next(
                g
                for g in games
                if g["model"] == PRIMARY
                and g["n"] == 32
                and g["noise"] == 0
                and sum(
                    not t["invalid"] and t["is_question"] and t["eig"] < 1e-12
                    for t in g["turns"]
                )
                >= 5
            ),
            "qwen-zero-information.md",
            "repeated legal zero-information questions",
        ),
        (
            next(
                g
                for g in games
                if g["model"] != PRIMARY
                and any(t["truncated"] and not t["action"] for t in g["turns"])
            ),
            "reference-analysis-only.md",
            "reference analysis truncation",
        ),
    ]
    for game, filename, reason in selected:
        transcript(game, records[game["game_id"]], filename, reason)
    result = {
        "source_sha256": hashlib.sha256(
            (ROOT / "results/phase2/games.jsonl.gz").read_bytes()
        ).hexdigest(),
        "service_calls": 0,
        "definitions": {
            "outcomes": "Valid ASK, valid GUESS, INVALID and other partition turns. Truncated and empty are overlapping flags. A second partition gives truncation priority.",
            "invalid_heavy": "At least half the counted questions returned INVALID. This overlaps terminal causes.",
            "zero_eig": "Valid primary questions with EIG < 1e-12. Constant full-table predicates are separate from predicates constant only after noiseless elimination.",
            "cost_bridge": "Change turn count at forecast lengths, then actual input lengths, then actual output lengths, then measured cache credit, then per-call upward rounding. Invalid cost is an observed subset, not an additive bridge term.",
        },
        "cells": cells,
        "zero_eig_categories": dict(Counter(z["category"] for z in zeros)),
        "zero_eig_requested_categories": dict(
            Counter(z["requested_category"] for z in zeros)
        ),
        "zero_eig_questions": zeros,
        "costs": costs,
        "transcripts": [
            {
                "file": filename,
                "model": g["model"],
                "game_id": g["game_id"],
                "selection": why,
            }
            for g, filename, why in selected
        ],
    }
    assert len(zeros) == 311
    assert sum(Decimal(c["actual_usd"]) for c in costs) == Decimal("5.793225")
    (OUT / "phase2.json").write_text(json.dumps(result, indent=2) + "\n")
    with (OUT / "turns.csv").open("w") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "model",
                "domain",
                "n",
                "noise",
                "games",
                "turns",
                "valid_ASK",
                "valid_GUESS",
                "INVALID",
                "other",
                "truncated",
                "empty",
            ],
        )
        writer.writeheader()
        for cell in cells:
            writer.writerow(
                {k: cell.get(k, cell["outcomes"].get(k, 0)) for k in writer.fieldnames}
            )
    print(
        json.dumps(
            {
                "games": len(games),
                "turns": sum(c["turns"] for c in cells),
                "zero_eig": result["zero_eig_categories"],
                "costs": costs,
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
